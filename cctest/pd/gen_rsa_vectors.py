# pd interim LLM-written test tooling, experimental, see README.md
# writes pd_rsa_vectors.h from wycheproof rsassa-pkcs1 json files and cavp 186-3 SigVer15 .rsp and SigGen15 .txt (it carries d)
# usage: gen_rsa_vectors.py out.h wycheproof/*.json cavp/SigVer15_186-3.rsp cavp/SigGen15_186-3.txt
import hashlib, json, os, sys

hashes = {'SHA-1': 'sha1', 'SHA-224': 'sha224', 'SHA-256': 'sha256', 'SHA-384': 'sha384', 'SHA-512': 'sha512',
          'SHA1': 'sha1', 'SHA224': 'sha224', 'SHA256': 'sha256', 'SHA384': 'sha384', 'SHA512': 'sha512'}
keys, rows, nulloid = {}, [], []

def key(n, e):
    n, e = n.lower().lstrip('0') or '0', e.lower()
    if len(n) % 2: n = '0' + n
    if len(e) % 2: e = '0' + e
    if (n, e) not in keys:
        keys[(n, e)] = 'k%d' % len(keys)
    return keys[(n, e)]

def row(src, k, h, msg, sig, expect):
    rows.append('{ "%s", %s_n, %s_e, di_%s, "%s", "%s", %d }' % (src, k, k, h, hashlib.new(h, msg).hexdigest(), sig, expect))

for path in sys.argv[2:]:
    base = os.path.basename(path)
    if path.endswith('.json'):
        d = json.load(open(path))
        assert d['schema'] == 'rsassa_pkcs1_verify_schema_v1.json'
        for g in d['testGroups']:
            k = key(g['publicKey']['modulus'], g['publicKey']['publicExponent'])
            for t in g['tests']:
                expect = {'valid': 1, 'invalid': 0, 'acceptable': 2}[t['result']]
                row('%s#%d' % (base, t['tcId']), k, hashes[g['sha']], bytes.fromhex(t['msg']), t['sig'], expect)
        continue
    n = e = h = msg = sig = None
    count = 0
    for line in open(path):
        line = line.strip()
        if '=' not in line or line.startswith('#') or line.startswith('['):
            continue
        a, b = [x.strip() for x in line.split('=', 1)]
        if a == 'n': n = b
        elif a == 'e': e = b
        elif a == 'SHAAlg': h = hashes[b]
        # some SigVer15 failure vectors carry an odd-length (altered) message, pad it
        elif a == 'Msg': msg = bytes.fromhex(b if len(b) % 2 == 0 else '0' + b)
        elif a == 'd': d = int(b, 16)
        elif a == 'S':
            # cavp gives S as an integer, i2osp it to the modulus length
            sig = b.rjust(2 * ((int(n, 16).bit_length() + 7) // 8), '0')
            if 'SigGen' in base:
                if not nulloid:
                    # rfc 4346 4.7 style, T = md5 || sha1 with no digestinfo, signed with the cavp key's d
                    t = hashlib.md5(msg).digest() + hashlib.sha1(msg).digest()
                    k = (int(n, 16).bit_length() + 7) // 8
                    em = b'\x00\x01' + b'\xff' * (k - len(t) - 3) + b'\x00' + t
                    s = pow(int.from_bytes(em, 'big'), d, int(n, 16)).to_bytes(k, 'big')
                    nulloid.append('{ "%s null oid", %s_n, %s_e, NULL, "%s", "%s", 1 }' % (base, key(n, e), key(n, e), t.hex(), s.hex()))
                count += 1
                row('%s#%d' % (base, count), key(n, e), h, msg, sig, 1)
        elif a == 'Result':
            count += 1
            row('%s#%d' % (base, count), key(n, e), h, msg, sig, 1 if b.startswith('P') else 0)

with open(sys.argv[1], 'w') as f:
    f.write('// generated by gen_rsa_vectors.py, do not edit\n')
    f.write('// sources: wycheproof testvectors_v1 rsa_signature_*_test.json, nist cavp 186-3rsatestvectors SigVer15_186-3.rsp and SigGen15_186-3.txt\n')
    for (n, e), k in keys.items():
        f.write('static const char %s_n[] = "%s";\nstatic const char %s_e[] = "%s";\n' % (k, n, k, e))
    f.write('static const struct pd_rsa_vec pd_rsa_vecs[] = {\n    %s\n};\n' % ',\n    '.join(rows))
    f.write('static const struct pd_rsa_vec pd_rsa_nulloid_vecs[] = {\n    %s\n};\n' % ',\n    '.join(nulloid))
print(len(keys), 'keys', len(rows), 'vectors')
